"""A device-tree include that absorbs the ABL's board overlay.

Booting, the PICO 4's ABL lays a downstream board overlay (the dtbo partition, or a recovery
image's recovery_dtbo) over the kernel's device tree. Its fragments target downstream labels
(`spmi_bus`, `tlmm`, `soc`, ...), several of which a mainline tree has too: applied to those,
the overlay would add downstream PMIC, pinctrl and SoC nodes to live mainline nodes. The tree is
therefore built without dtc's own symbol table, and this include provides one: every label any
of the overlays refers to resolves to an empty node below /pico4-dtbo-sink, which has no
compatible, so no driver ever binds to what the overlay puts there.

    python dtbo_sink.py IMAGE OUT.dtsi

IMAGE is an Android dtbo image or a boot image whose recovery_dtbo holds one.
"""
from __future__ import annotations

import re
import struct
import sys
from pathlib import Path

DTBO_MAGIC = 0xD7B7AB1E
FDT_MAGIC = 0xD00DFEED
SINK = "pico4-dtbo-sink"


def overlays(data: bytes) -> list[bytes]:
    """The overlays of an Android dtbo image (the dtbo partition or a recovery_dtbo)."""
    magic, _total, _header, entry_size, count, offset = struct.unpack(">IIIIII", data[:24])
    if magic != DTBO_MAGIC:
        raise ValueError("not an Android dtbo image")
    result = []
    for i in range(count):
        size, start = struct.unpack(">II", data[offset + i * entry_size:offset + i * entry_size + 8])
        blob = data[start:start + size]
        if struct.unpack(">I", blob[:4])[0] != FDT_MAGIC:
            raise ValueError(f"overlay {i} is not a flattened device tree")
        result.append(blob)
    return result


def fixup_labels(fdt: bytes) -> set[str]:
    """The labels an overlay's __fixups__ node names (its property names)."""
    _magic, _total, off_struct, off_strings, *_ = struct.unpack(">IIIIIIIIII", fdt[:40])
    strings = fdt[off_strings:]
    labels, depth, path, pos = set(), 0, [], off_struct
    while True:
        token = struct.unpack(">I", fdt[pos:pos + 4])[0]
        pos += 4
        if token == 1:  # FDT_BEGIN_NODE
            end = fdt.index(b"\0", pos)
            path.append(fdt[pos:end].decode())
            pos = (end + 4) & ~3
        elif token == 2:  # FDT_END_NODE
            path.pop()
        elif token == 3:  # FDT_PROP
            length, name_off = struct.unpack(">II", fdt[pos:pos + 8])
            pos = (pos + 8 + length + 3) & ~3
            if path[-1:] == ["__fixups__"] and len(path) == 2:
                labels.add(strings[name_off:strings.index(b"\0", name_off)].decode())
        elif token == 4:  # FDT_NOP
            continue
        elif token == 9:  # FDT_END
            return labels
        else:
            raise ValueError(f"bad structure token {token:#x}")


def dtbo_of(path: Path) -> bytes:
    data = path.read_bytes()
    if struct.unpack(">I", data[:4])[0] == DTBO_MAGIC:
        return data
    sys.path.insert(0, str(Path(__file__).resolve().parents[3]))
    from overpressure import bootimg
    dtbo = bootimg.parse(data).recovery_dtbo
    if not dtbo:
        raise ValueError(f"{path} has no recovery_dtbo")
    return dtbo


def sink(labels: set[str]) -> str:
    for label in labels:
        if not re.fullmatch(r"[A-Za-z0-9_]+", label):
            raise ValueError(f"unexpected label {label!r}")
    names = sorted(labels)
    lines = ["// Generated by dtbo_sink.py: absorbs the ABL's board overlay.", "", "/ {",
             f"\t{SINK} {{",
             # Every node needs a phandle for the ABL to resolve a fixup to it; a reference makes
             # dtc give it one.
             "\t\tpico4,refs = <" + " ".join(f"&dtbo_{n}" for n in names) + ">;", ""]
    lines += [f"\t\tdtbo_{n}: {n} {{\n\t\t}};" for n in names]
    lines += ["\t};", "", "\t__symbols__ {"]
    lines += [f'\t\t{n} = "/{SINK}/{n}";' for n in names]
    lines += ["\t};", "};", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 2:
        print("usage: python dtbo_sink.py IMAGE OUT.dtsi", file=sys.stderr)
        return 2
    labels = set()
    for overlay in overlays(dtbo_of(Path(argv[0]))):
        labels |= fixup_labels(overlay)
    Path(argv[1]).write_text(sink(labels), encoding="utf-8", newline="\n")
    print(f"{len(labels)} overlay labels -> {argv[1]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
