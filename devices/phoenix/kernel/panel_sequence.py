"""The PICO 4 panels' command sequences, taken from the stock board overlay at build time.

The panels' power-on and power-off commands are PICO's data, so they stay out of the
repository: this generates a device-tree include that gives them to the panel driver as
`pico4,on-command` and `pico4,off-command`, copied from the stock panel node
(`qcom,mdss_dsi_sharp_ls026b3sa_90_video`, timing@0) of the board overlay in the stock recovery
image. The format stays the downstream one: per command its data type, a "last" flag, the
virtual channel, an acknowledge flag, the delay after it in ms, the payload length (big endian)
and the payload.

    python panel_sequence.py IMAGE OUT.dtsi

IMAGE is an Android dtbo image or a boot image whose recovery_dtbo holds one.
"""
from __future__ import annotations

import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import dtbo_sink  # noqa: E402

PANEL = ("qcom,mdss_dsi_sharp_ls026b3sa_90_video", "qcom,mdss-dsi-display-timings", "timing@0")
#: Stock property -> the panel driver's.
SEQUENCES = {"qcom,mdss-dsi-on-command": "pico4,on-command",
             "qcom,mdss-dsi-off-command": "pico4,off-command"}
#: DSI data types the stock sequences may use: generic and DCS writes, short and long.
WRITE_TYPES = {0x03, 0x13, 0x23, 0x29, 0x05, 0x15, 0x39}
LABEL = "display_panel"


def node_properties(fdt: bytes, names: tuple) -> dict | None:
    """The properties of the first node whose path ends with `names`, or None."""
    _magic, _total, off_struct, off_strings, *_ = struct.unpack(">IIIIIIIIII", fdt[:40])
    strings = fdt[off_strings:]
    path, pos, found = [], off_struct, None
    while True:
        token = struct.unpack(">I", fdt[pos:pos + 4])[0]
        pos += 4
        if token == 1:  # FDT_BEGIN_NODE
            end = fdt.index(b"\0", pos)
            path.append(fdt[pos:end].decode())
            pos = (end + 4) & ~3
            if found is None and tuple(path[-len(names):]) == names:
                found, depth = {}, len(path)
        elif token == 2:  # FDT_END_NODE
            if found is not None and len(path) == depth:
                return found
            path.pop()
        elif token == 3:  # FDT_PROP
            length, name_off = struct.unpack(">II", fdt[pos:pos + 8])
            value = fdt[pos + 8:pos + 8 + length]
            pos = (pos + 8 + length + 3) & ~3
            if found is not None and len(path) == depth:
                found[strings[name_off:strings.index(b"\0", name_off)].decode()] = value
        elif token == 4:  # FDT_NOP
            continue
        elif token == 9:  # FDT_END
            return None
        else:
            raise ValueError(f"bad structure token {token:#x}")


def commands(sequence: bytes) -> list[tuple[int, int, bytes]]:
    """(data type, delay in ms, payload) for each command; refuses anything but writes."""
    result, pos = [], 0
    while pos < len(sequence):
        if pos + 7 > len(sequence):
            raise ValueError("truncated command header")
        dtype, _last, channel, ack, delay, length = struct.unpack(">BBBBBH", sequence[pos:pos + 7])
        payload = sequence[pos + 7:pos + 7 + length]
        if dtype not in WRITE_TYPES or channel or ack or len(payload) != length or not length:
            raise ValueError(f"unexpected command at byte {pos}: type {dtype:#x}, {length} bytes")
        result.append((dtype, delay, payload))
        pos += 7 + length
    return result


def sequences(dtbo: bytes) -> dict[str, bytes]:
    """The panel's sequences, which every board overlay that has the panel must agree on."""
    found = []
    for overlay in dtbo_sink.overlays(dtbo):
        props = node_properties(overlay, PANEL)
        if props is not None:
            found.append({name: props[name] for name in SEQUENCES if name in props})
    if not found:
        raise ValueError("no board overlay has the LS026B3SA panel")
    if any(f != found[0] for f in found) or set(found[0]) != set(SEQUENCES):
        raise ValueError("the board overlays disagree on the panel's command sequences")
    for value in found[0].values():
        commands(value)
    return found[0]


def include(seqs: dict[str, bytes]) -> str:
    lines = ["// Generated by panel_sequence.py from the stock board overlay: the panels' commands.",
             "", f"&{LABEL} {{"]
    for stock, ours in SEQUENCES.items():
        lines.append(f"\t{ours} = [{seqs[stock].hex(' ')}];")
    lines += ["};", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 2:
        print("usage: python panel_sequence.py IMAGE OUT.dtsi", file=sys.stderr)
        return 2
    seqs = sequences(dtbo_sink.dtbo_of(Path(argv[0])))
    Path(argv[1]).write_bytes((include(seqs)).encode("utf-8"))
    counts = ", ".join(f"{len(commands(v))} {k.split('-')[-2]}" for k, v in seqs.items())
    print(f"panel commands ({counts}) -> {argv[1]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
